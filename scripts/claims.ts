/**
 * pnpm claims: build CLAIMS.md from the test reports and fail when a claim ID
 * in the README or TESTING.md has no test, or when any of its tests failed.
 * The NER claims show as skipped when their model tests did not run.
 * `--strict` (what `pnpm verify` uses) fails on those too.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from '../test/support/corpus.js';
import { claimStatus, evaluateClaims, loadMutation, mutationFloor } from './lib/claims.js';

const strict = process.argv.includes('--strict');
const { claims, problems, testCount } = evaluateClaims({ strict });

const lines: string[] = [
  '# Claims',
  '',
  'Generated by `pnpm claims` from the last `pnpm test` report. Do not edit by hand. The plan behind each row is in [TESTING.md](TESTING.md).',
  '',
];
if (claims.length) {
  lines.push(`${claims.length} claims, ${testCount} tests in the report.`, '', '| ID | Claim | Tests | Result |', '| --- | --- | --- | --- |');
  for (const c of claims) {
    const n = `${c.passed}/${c.tests.length}`;
    lines.push(`| ${c.id} | ${c.text.replace(/\|/g, '\\|')} | ${n} | ${claimStatus(c)} |`);
  }
  const m = loadMutation();
  lines.push('', `Mutation score at the last \`pnpm mutation\` run: ${m ? `${m.score.toFixed(2)}%` : 'no report yet'}, floor ${mutationFloor()}%.`);
  lines.push('', '## Tests by claim', '');
  for (const c of claims) {
    lines.push(`### ${c.id}`, '');
    for (const t of c.tests) lines.push(`- ${t.status === 'passed' ? 'pass' : t.status}: ${t.title}`);
    if (c.tests.length === 0) lines.push('- no test');
    for (const n of c.notes) lines.push(`- ${n}`);
    lines.push('');
  }
} else {
  lines.push('No test report yet.');
}
writeFileSync(join(ROOT, 'CLAIMS.md'), `${lines.join('\n')}\n`);

if (problems.length) {
  console.error(`claims check failed:\n  ${problems.join('\n  ')}`);
  process.exit(1);
}
const skipped = claims.filter((c) => c.notes.length).length;
console.log(skipped ? `CLAIMS.md written. ${claims.length} claims, ${skipped} skipped (NER tests did not run), the rest backed by passing tests.` : `CLAIMS.md written. ${claims.length} claims, all backed by passing tests.`);
